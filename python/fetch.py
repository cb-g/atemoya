"""Fetch tickers' fundamentals and write boundary JSON.

    uv run python/fetch.py AAPL [MSFT ...]     ->   data/financials/<TICKER>.json

Statements come from filed 10-Ks or 20-Fs (SEC XBRL companyfacts, via fetch_sec.py) when
the ticker resolves exactly to an annual filer under us-gaap or ifrs-full, otherwise from
yfinance, and the record says which, why, in which taxonomy and in which currency. Price, market cap and currencies always come from yfinance. For every
XBRL-primary name the vendor's statements are fetched too and compared field by field for
the latest common period (cross_check on the record: recorded, never a gate, never
resolved), and the vendor's full record is written beside it as
<TICKER>.shadow-yfinance.json so the batch can value both and explain every moved number.
SEC's submissions index is read for every CIK-resolved name and its newest 10-K or 20-F
recorded; when that filing is newer than the newest annual facts and those facts are past
the filing-age gate, the vendor's statements are used by a decision written into
provider_reason (companyfacts lags submissions), never as a fallback from the gate.

Vendor pipeline: yfinance -> pydantic (validated vendor snapshot) -> boundary dataclasses
(generated by atdpy from schema/boundary.atd) -> JSON.

Everything yfinance-specific -- row labels, sign conventions, `.info` keys -- stays in
this file, except the four composed fields: cash, total debt, the change in working
capital and ebit take their vendor rows from reference/field_definitions.json, the one
definition the filed-statement path follows too, and every period records the components
summed. What leaves it is `boundary.Financials`: canonical, vendor-neutral, one currency
basis, explicit None wherever the vendor supplied nothing usable. A ticker that cannot be
fetched still yields a record, with nulls and a note, so the valuation reports Failed for
it rather than silently skipping it.
"""

