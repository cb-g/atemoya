# (component name in the definition, value as summed, vendor row label): a composed
# field's audit trail, carried through the validated snapshot into the boundary record.
type Components = list[tuple[str, float, str]]


# --- pydantic: the vendor's data, validated ------------------------------------------
# yfinance output is untrusted. It is parsed into these models or it raises; the data
# rules live in the validators. Field names and signs are already canonical here.


# Vendor codes for prices quoted in a currency's minor unit -> (major code, divisor). The
# vendor's market cap is already in the major unit (AZN.L: price 12500 GBp, market cap
# 1.9e11 GBP), so only the price is divided; the field report's -98% on an LSE name was a
# pence price against a pounds fair value.
MINOR_UNITS: dict[str, tuple[str, float]] = {"GBp": ("GBP", 100.0), "GBX": ("GBP", 100.0), "ZAc": ("ZAR", 100.0), "ILA": ("ILS", 100.0)}


class Quote(BaseModel):
    """Price-level fields from `.info`. Only these: fundamentals come from statements,
    which are served from a more robust endpoint and are internally consistent. Per-share
    fields are never read: their currency is unreliable per field and per ticker."""

    model_config = ConfigDict(frozen=True, strict=True)

    currency: str | None  # trading currency of price and market_cap, as the vendor codes it
    financial_currency: str | None  # currency of the statements
    price: float | None  # as quoted, possibly in a minor unit
    market_cap: float | None  # in the major unit

    @field_validator("currency", "financial_currency")
    @classmethod
    def _currency_code(cls, v: str | None) -> str | None:
        if v is not None and not (len(v) == 3 and v.isalpha()):
            raise ValueError(f"not a currency code: {v!r}")
        return v

    @property
    def trading_currency(self) -> str | None:
        """The major-unit code of the price's currency."""
        return MINOR_UNITS[self.currency][0] if self.currency in MINOR_UNITS else self.currency

    @property
    def price_unit_divisor(self) -> float:
        return MINOR_UNITS[self.currency][1] if self.currency in MINOR_UNITS else 1.0

    @property
    def major_price(self) -> float | None:
        return None if self.price is None else self.price / self.price_unit_divisor

    @field_validator("price", "market_cap")
    @classmethod
    def _finite_positive(cls, v: float | None) -> float | None:
        if v is not None and not (math.isfinite(v) and v > 0):
            raise ValueError(f"expected a finite positive number, got {v!r}")
        return v


class Profile(BaseModel):
    """Domicile and industry from `.info`, used only as lookup keys into reference/.
    Both come back empty under load, so both are nullable; blank strings are absent."""

    model_config = ConfigDict(frozen=True, strict=True)

    country: str | None
    industry: str | None

    @field_validator("country", "industry", mode="before")
    @classmethod
    def _blank_is_absent(cls, v: object) -> object:
        if isinstance(v, str):
            return v.strip() or None
        return v


NON_NEGATIVE = frozenset(
    {
        "total_revenue",
        "premiums_earned",
        "reconciled_depreciation",
        "depreciation_amortization",
        "capex",
        "cash",
        "total_debt",
        "dividends_paid",
        "provision_for_credit_losses",
        "net_loans",
    }
)


class Statement(BaseModel):
    """One statement for one fiscal period, in the boundary's field names and signs."""

    model_config = ConfigDict(frozen=True, strict=True)

    period_end: date

    @field_validator("*", mode="before")
    @classmethod
    def _nan_is_absent(cls, v: object) -> object:
        # yfinance encodes "not reported" as NaN inside float64 frames. An infinity is
        # never a legitimate statement value.
        if isinstance(v, float):
            if math.isnan(v):
                return None
            if math.isinf(v):
                raise ValueError("infinite value")
        return v

    @field_validator("*")
    @classmethod
    def _sign_rules(cls, v: object, info: ValidationInfo) -> object:
        if info.field_name in NON_NEGATIVE and isinstance(v, float) and v < 0:
            raise ValueError(f"{info.field_name} must be >= 0, got {v}")
        return v


class IncomeStatement(Statement):
    ebit: float | None
    ebit_row: str | None
    ebit_recipe: str | None  # operating_income | pretax_plus_interest, per the definition
    ebit_composition: Components | None
    pretax_income: float | None
    tax_provision: float | None
    total_revenue: float | None
    net_interest_income: float | None
    premiums_earned: float | None
    premiums_earned_row: str | None  # the vendor row label that supplied premiums_earned
    reconciled_depreciation: float | None  # the income statement's depreciation line, a D&A fallback
    net_income: float | None
    provision_for_credit_losses: float | None
    provision_for_credit_losses_row: str | None


class CashFlowStatement(Statement):
    depreciation_amortization: float | None
    depreciation_amortization_row: str | None
    capex: float | None
    delta_nwc: float | None
    delta_nwc_row: str | None
    delta_nwc_composition: Components | None
    dividends_paid: float | None  # positive = cash paid
    dividends_paid_row: str | None


class BalanceSheet(Statement):
    cash: float | None
    cash_row: str | None
    cash_composition: Components | None
    total_debt: float | None
    total_debt_source: str | None  # the row, or row sum, that supplied total_debt
    total_debt_composition: Components | None
    book_equity: float | None
    net_loans: float | None
    net_loans_row: str | None


# --- yfinance specifics -------------------------------------------------------------
# Vendor row label and sign per boundary field. Sign -1 converts the cash-flow
# statement's convention (outflows negative, working-capital release positive) into the
# boundary's (capex = cash spent, delta_nwc = increase in net working capital).
# Verified on yfinance 1.7.0: Operating Cash Flow minus |Capital Expenditure| reproduces
# the vendor's own Free Cash Flow row.

type RowSpec = Mapping[str, tuple[str, float]]

INCOME_ROWS: RowSpec = {
    "pretax_income": ("Pretax Income", 1.0),
    "tax_provision": ("Tax Provision", 1.0),
    "total_revenue": ("Total Revenue", 1.0),
    "net_interest_income": ("Net Interest Income", 1.0),
    "reconciled_depreciation": ("Reconciled Depreciation", 1.0),
    "net_income": ("Net Income", 1.0),
}
# Bank rows. None of the provision labels exists on any bank on yfinance 1.7.0 (2026-09-18);
# kept so a vendor that does expose one is read, and the matched label is recorded.
PROVISION_ROWS = (
    "Credit Losses Provision",
    "Provision For Loan Losses",
    "Provision For Credit Losses",
    "Provision For Doubtful Accounts",
)
DIVIDEND_ROWS = ("Cash Dividends Paid", "Common Stock Dividend Paid")  # outflows, negative on the vendor's statement
NET_LOAN_ROWS = ("Net Loan", "Net Loans", "Loans Receivable")
# Insurer signature: the first of these rows that carries a value. Verified absent for
# ALL, MET, PGR and ALV.DE on yfinance 1.7.0 (2026-09-18); kept so a vendor that does
# expose one is read, and the matched label is recorded for audit.
PREMIUM_ROWS = (
    "Net Premiums Earned",
    "Total Premiums Earned",
    "Premiums Earned",
    "Insurance Premiums",
    "Net Premium Earned",
)
CASHFLOW_ROWS: RowSpec = {
    "capex": ("Capital Expenditure", -1.0),
}
# D&A: the first of these cash-flow rows that carries a value, then the income statement's
# "Reconciled Depreciation". XOM files only "Depreciation Amortization Depletion"; the
# matched label is recorded so the audit trail says where the add-back came from.
DNA_ROWS = ("Depreciation And Amortization", "Depreciation Amortization Depletion", "Depreciation")
RECONCILED_DEPRECIATION_ROW = "Reconciled Depreciation"
BALANCE_ROWS: RowSpec = {
    "book_equity": ("Stockholders Equity", 1.0),
}
# cash, total_debt, delta_nwc and ebit: rows and recipes from reference/field_definitions.json
# (DEFINITIONS), never from this file. Never a substituted zero: a missing required row
# leaves the field absent, as the previous implementation's 0.0 default for Total Debt
# overstated equity value.


def _columns(frame: pd.DataFrame) -> dict[date, dict[str, object]]:
    """Statement frames: one column per fiscal period end, vendor row labels as index."""
    out: dict[date, dict[str, object]] = {}
    for column, rows in frame.to_dict().items():
        if not isinstance(column, datetime):  # pd.Timestamp is a datetime
            raise TypeError(f"period column is {type(column).__name__}, not a timestamp")
        out[column.date()] = {str(label): value for label, value in rows.items()}
    return out


def _canonical_values(rows: Mapping[str, object], spec: RowSpec) -> dict[str, object]:
    out: dict[str, object] = {}
    for field, (label, sign) in spec.items():
        value = rows.get(label)
        if isinstance(value, (int, float)) and not isinstance(value, bool):
            value = float(value) * sign
        out[field] = value
    return out


def _first_present(rows: Mapping[str, object], labels: tuple[str, ...]) -> tuple[float | None, str | None]:
    for label in labels:
        value = rows.get(label)
        if isinstance(value, (int, float)) and not isinstance(value, bool) and not math.isnan(value):
            return float(value), label
    return None, None


def _cash(rows: Mapping[str, object], defs: reference.FieldDefinitions) -> tuple[float | None, str | None, Components | None]:
    """Cash and equivalents plus the short-term investments row when it carries a value."""
    d = defs.cash.vendor
    equivalents, row = _first_present(rows, tuple(d.cash_equivalents))
    if equivalents is None or row is None:
        return None, None, None
    parts: Components = [("cash_equivalents", equivalents, row)]
    investments, investments_row = _first_present(rows, tuple(d.short_term_investments))
    if investments is not None and investments_row is not None:
        parts.append(("short_term_investments", investments, investments_row))
    return sum(v for _, v, _ in parts), " + ".join(r for _, _, r in parts), parts


def _total_debt(rows: Mapping[str, object], defs: reference.FieldDefinitions) -> tuple[float | None, str | None, Components | None]:
    """Long-term debt, plus the current-debt row when present (it already holds commercial
    paper), else its components when either is present. The vendor's Total Debt and lease
    rows are never read: Total Debt includes the operating lease liabilities."""
    d = defs.total_debt.vendor
    long_term, row = _first_present(rows, tuple(d.long_term_debt))
    if long_term is None or row is None:
        return None, None, None
    parts: Components = [("long_term_debt", long_term, row)]
    current, current_row = _first_present(rows, tuple(d.current_debt))
    if current is not None and current_row is not None:
        parts.append(("current_debt", current, current_row))
    else:
        for label in d.current_debt_components:
            value, component_row = _first_present(rows, (label,))
            if value is not None and component_row is not None:
                parts.append(("current_debt_components", value, component_row))
    return sum(v for _, v, _ in parts), " + ".join(r for _, _, r in parts), parts


def _delta_nwc(rows: Mapping[str, object], defs: reference.FieldDefinitions) -> tuple[float | None, str | None, Components | None]:
    """The vendor's change-in-working-capital line, flipped into the boundary's sign."""
    d = defs.delta_nwc.vendor
    value, row = _first_present(rows, tuple(d.change_in_working_capital))
    if value is None or row is None:
        return None, None, None
    signed = value * d.sign
    return signed, row, [("change_in_working_capital", signed, row)]


def _ebit(rows: Mapping[str, object], defs: reference.FieldDefinitions) -> tuple[float | None, str | None, str | None, Components | None]:
    """Operating income; else pretax income plus interest expense less the non-operating
    income rows (each first present), recorded as the recipe
    pretax_plus_interest_less_nonoperating. (value, row, recipe, components)."""
    d = defs.ebit.vendor
    operating, row = _first_present(rows, tuple(d.operating_income))
    if operating is not None and row is not None:
        return operating, row, "operating_income", [("operating_income", operating, row)]
    pretax, pretax_row = _first_present(rows, (INCOME_ROWS["pretax_income"][0],))
    interest, interest_row = _first_present(rows, tuple(d.interest_expense))
    if pretax is None or pretax_row is None or interest is None or interest_row is None:
        return None, None, None, None
    parts: Components = [("pretax_income", pretax, pretax_row), ("interest_expense", interest, interest_row)]
    label = f"{pretax_row} + {interest_row}"
    for name, labels in (("interest_income", d.interest_income), ("other_nonoperating", d.other_nonoperating), ("equity_method", d.equity_method)):
        value, value_row = _first_present(rows, tuple(labels))
        if value is not None and value_row is not None:
            parts.append((name, -value, value_row))
            label += f" - {value_row}"
    return sum(v for _, v, _ in parts), label, "pretax_plus_interest_less_nonoperating", parts


def _income_values(rows: Mapping[str, object], defs: reference.FieldDefinitions = DEFINITIONS) -> dict[str, object]:
    out = _canonical_values(rows, INCOME_ROWS)
    out["ebit"], out["ebit_row"], out["ebit_recipe"], out["ebit_composition"] = _ebit(rows, defs)
    out["premiums_earned"], out["premiums_earned_row"] = _first_present(rows, PREMIUM_ROWS)
    out["provision_for_credit_losses"], out["provision_for_credit_losses_row"] = _first_present(rows, PROVISION_ROWS)
    return out


def _cashflow_values(rows: Mapping[str, object], defs: reference.FieldDefinitions = DEFINITIONS) -> dict[str, object]:
    out = _canonical_values(rows, CASHFLOW_ROWS)
    out["delta_nwc"], out["delta_nwc_row"], out["delta_nwc_composition"] = _delta_nwc(rows, defs)
    out["depreciation_amortization"], out["depreciation_amortization_row"] = _first_present(rows, DNA_ROWS)
    dividends, row = _first_present(rows, DIVIDEND_ROWS)
    out["dividends_paid"], out["dividends_paid_row"] = (None if dividends is None else 0.0 - dividends), row
    return out


def _balance_values(rows: Mapping[str, object], defs: reference.FieldDefinitions = DEFINITIONS) -> dict[str, object]:
    out = _canonical_values(rows, BALANCE_ROWS)
    out["cash"], out["cash_row"], out["cash_composition"] = _cash(rows, defs)
    out["total_debt"], out["total_debt_source"], out["total_debt_composition"] = _total_debt(rows, defs)
    out["net_loans"], out["net_loans_row"] = _first_present(rows, NET_LOAN_ROWS)
    return out


def _info(ticker: yf.Ticker, notes: list[str]) -> tuple[Quote | None, Profile | None]:
    """One `.info` call, validated as two independent models so a bad price does not
    lose the country, or vice versa."""
    try:
        info = ticker.info
    except Exception as e:  # the vendor call is the untrusted edge; any failure is a note
        notes.append(f"info: vendor failed: {type(e).__name__}: {e}")
        return None, None
    quote: Quote | None = None
    profile: Profile | None = None
    try:
        quote = Quote.model_validate(
            {
                "currency": info.get("currency"),
                "financial_currency": info.get("financialCurrency"),
                "price": info.get("regularMarketPrice"),
                "market_cap": info.get("marketCap"),
            }
        )
    except ValidationError as e:
        notes.append(f"quote: rejected: {e}")
    try:
        profile = Profile.model_validate({"country": info.get("country"), "industry": info.get("industry")})
    except ValidationError as e:
        notes.append(f"profile: rejected: {e}")
    return quote, profile


def _statement[S: Statement](
    ticker: yf.Ticker,
    load: Callable[[yf.Ticker], pd.DataFrame],
    name: str,
    model: type[S],
    canonical: Callable[[Mapping[str, object]], dict[str, object]],
    notes: list[str],
) -> dict[date, S]:
    """Every fiscal period of one statement that validates; the rest become notes."""
    try:
        columns = _columns(load(ticker))
    except Exception as e:
        notes.append(f"{name}: vendor failed: {type(e).__name__}: {e}")
        return {}
    out: dict[date, S] = {}
    for period_end, rows in columns.items():
        try:
            out[period_end] = model.model_validate(
                {"period_end": period_end, **canonical(rows)}
            )
        except ValidationError as e:
            notes.append(f"{name} {period_end}: rejected: {e}")
    return out


# --- canonical record ---------------------------------------------------------------


def _single_currency(quote: Quote, notes: list[str]) -> str | None:
    """One basis for price, market cap and statements, or None. A mismatch is the
    cross-currency path's job downstream; it is noted here, never converted or assumed."""
    if quote.trading_currency is not None and quote.trading_currency == quote.financial_currency:
        return quote.trading_currency
    notes.append(
        f"no single currency basis: price currency {quote.trading_currency!r}, "
        f"statement currency {quote.financial_currency!r}"
    )
    return None


def quote_fields(quote: Quote | None, notes: list[str]) -> dict[str, object]:
    """The currency, unit and price fields of a boundary record from a validated quote."""
    if quote is None:
        return {"currency": None, "financial_currency": None, "trading_currency": None,
                "price_unit": boundary.PriceUnit(boundary.Major()), "price_unit_divisor": 1.0,
                "price": None, "market_cap": None}
    minor = quote.currency in MINOR_UNITS
    if minor:
        notes.append(f"price quoted in {quote.currency}: divided by {quote.price_unit_divisor:g} to {quote.trading_currency}; market cap already in {quote.trading_currency}")
    return {"currency": _single_currency(quote, notes),
            "financial_currency": quote.financial_currency, "trading_currency": quote.trading_currency,
            "price_unit": boundary.PriceUnit(boundary.Minor() if minor else boundary.Major()),
            "price_unit_divisor": quote.price_unit_divisor,
            "price": quote.major_price, "market_cap": quote.market_cap}


def _depreciation(
    income: IncomeStatement | None, cashflow: CashFlowStatement | None
) -> tuple[float | None, str | None]:
    if cashflow is not None and cashflow.depreciation_amortization is not None:
        return cashflow.depreciation_amortization, cashflow.depreciation_amortization_row
    if income is not None and income.reconciled_depreciation is not None:
        return income.reconciled_depreciation, RECONCILED_DEPRECIATION_ROW
    return None, None


def _composition(definition: str, parts: Components | None) -> boundary.Composition | None:
    if parts is None:
        return None
    return boundary.Composition(definition=definition, components=[boundary.Component(name=n, value=v, row=r) for n, v, r in parts])


def _period(
    end: date,
    income: IncomeStatement | None,
    cashflow: CashFlowStatement | None,
    balance: BalanceSheet | None,
    defs: reference.FieldDefinitions = DEFINITIONS,
) -> boundary.FiscalPeriod:
    depreciation_amortization, depreciation_amortization_row = _depreciation(income, cashflow)
    return boundary.FiscalPeriod(
        period_end=end.isoformat(),
        ebit=income.ebit if income else None,
        ebit_row=income.ebit_row if income else None,
        ebit_recipe=income.ebit_recipe if income else None,
        ebit_composition=_composition(defs.ebit.name, income.ebit_composition) if income else None,
        pretax_income=income.pretax_income if income else None,
        tax_provision=income.tax_provision if income else None,
        total_revenue=income.total_revenue if income else None,
        net_interest_income=income.net_interest_income if income else None,
        premiums_earned=income.premiums_earned if income else None,
        premiums_earned_row=income.premiums_earned_row if income else None,
        depreciation_amortization=depreciation_amortization,
        depreciation_amortization_row=depreciation_amortization_row,
        capex=cashflow.capex if cashflow else None,
        delta_nwc=cashflow.delta_nwc if cashflow else None,
        delta_nwc_row=cashflow.delta_nwc_row if cashflow else None,
        delta_nwc_composition=_composition(defs.delta_nwc.name, cashflow.delta_nwc_composition) if cashflow else None,
        cash=balance.cash if balance else None,
        cash_row=balance.cash_row if balance else None,
        cash_composition=_composition(defs.cash.name, balance.cash_composition) if balance else None,
        total_debt=balance.total_debt if balance else None,
        total_debt_source=balance.total_debt_source if balance else None,
        total_debt_composition=_composition(defs.total_debt.name, balance.total_debt_composition) if balance else None,
        book_equity=balance.book_equity if balance else None,
        net_income=income.net_income if income else None,
        dividends_paid=cashflow.dividends_paid if cashflow else None,
        dividends_paid_row=cashflow.dividends_paid_row if cashflow else None,
        provision_for_credit_losses=income.provision_for_credit_losses if income else None,
        provision_for_credit_losses_row=income.provision_for_credit_losses_row if income else None,
        net_loans=balance.net_loans if balance else None,
        net_loans_row=balance.net_loans_row if balance else None,
    )


def _is_empty(period: boundary.FiscalPeriod) -> bool:
    labels = {
        "period_end",
        "premiums_earned_row",
        "depreciation_amortization_row",
        "total_debt_source",
        "dividends_paid_row",
        "provision_for_credit_losses_row",
        "net_loans_row",
        "ebit_row", "ebit_recipe", "ebit_composition", "delta_nwc_row", "delta_nwc_composition",
        "cash_row", "cash_composition", "total_debt_composition",
    }
    return all(getattr(period, f.name) is None for f in fields(period) if f.name not in labels)


def vendor_periods(ticker: yf.Ticker, notes: list[str]) -> list[boundary.FiscalPeriod]:
    income = _statement(ticker, lambda t: t.income_stmt, "income statement", IncomeStatement, _income_values, notes)
    cashflow = _statement(ticker, lambda t: t.cashflow, "cash flow statement", CashFlowStatement, _cashflow_values, notes)
    balance = _statement(ticker, lambda t: t.balance_sheet, "balance sheet", BalanceSheet, _balance_values, notes)
    periods: list[boundary.FiscalPeriod] = []
    for end in sorted(income.keys() | cashflow.keys() | balance.keys(), reverse=True):
        period = _period(end, income.get(end), cashflow.get(end), balance.get(end))
        if _is_empty(period):
            notes.append(f"{end}: omitted, every statement field absent")
        else:
            periods.append(period)
    return periods


# The core fields the two providers are compared on, for the latest common period.
CROSS_CHECK_FIELDS = (
    "total_revenue", "ebit", "pretax_income", "tax_provision", "net_interest_income", "depreciation_amortization",
    "capex", "delta_nwc", "cash", "total_debt", "book_equity", "net_income", "dividends_paid",
)
CROSS_CHECK_MAX_DAYS = 10  # the vendor rounds fiscal year ends to month ends


def match_period(primary: boundary.FiscalPeriod, candidates: list[boundary.FiscalPeriod]) -> boundary.FiscalPeriod | None:
    end = date.fromisoformat(primary.period_end)
    best = min(candidates, key=lambda p: abs((date.fromisoformat(p.period_end) - end).days), default=None)
    if best is None or abs((date.fromisoformat(best.period_end) - end).days) > CROSS_CHECK_MAX_DAYS:
        return None
    return best


def cross_check(primary: boundary.FiscalPeriod, secondary: boundary.FiscalPeriod, threshold: float, provider: str) -> boundary.CrossCheck:
    checks: list[boundary.FieldCheck] = []
    disagreements = 0
    for field in CROSS_CHECK_FIELDS:
        p: float | None = getattr(primary, field)
        s: float | None = getattr(secondary, field)
        rel: float | None = None
        agree: bool | None = None
        if p is not None and s is not None:
            scale = max(abs(p), abs(s))
            rel = 0.0 if scale == 0 else abs(p - s) / scale
            agree = rel <= threshold
            if not agree:
                disagreements += 1
        checks.append(boundary.FieldCheck(field=field, primary=p, secondary=s, relative_difference=rel, agree=agree))
    return boundary.CrossCheck(provider=provider, period_end=primary.period_end, secondary_period_end=secondary.period_end,
                               threshold=threshold, fields=checks, disagreements=disagreements)


class SecContext:
    """What routing to filed statements needs: the identity, the ticker map, the tag map, the definitions,
    and the admissibility table and parameters that say how many periods a class's model needs (22)."""

    def __init__(self) -> None:
        self.user_agent = fetch_sec.identity()
        self.tickers = fetch_sec.tickers_table(self.user_agent)
        self.tags: reference.XbrlTags = fetch_sec.load_tags()
        self.definitions: reference.FieldDefinitions = DEFINITIONS
        self.admissibility: reference.Admissibility = reference.Admissibility.from_json_string((REFERENCE / "admissibility.json").read_text())
        self.params: reference.Params = reference.Params.from_json_string((REFERENCE / "params.json").read_text())


def periods_needed(entity_class: str | None, admissibility: reference.Admissibility, params: reference.Params) -> int:
    """Period depth is a property of the model (22): the mid-cycle window for a class whose
    first admissible model is dcf_midcycle, five for every other model or no class."""
    rule = dict(admissibility.classes).get(entity_class) if entity_class else None
    model = rule.admissible_models[0] if rule is not None and rule.admissible_models else None
    return params.midcycle_window_years.value if model == "dcf_midcycle" else fetch_sec.PERIODS_DEFAULT


def cik_of(symbol: str, table: Mapping[str, object], declared: str | None) -> tuple[str | None, str]:
    """The declared CIK (22) when the entry has one, else the ticker map's; and where it came from."""
    if declared:
        return declared, "declared in the universe entry, not the ticker map"
    return fetch_sec.cik_for(symbol, table), "SEC's ticker map"


def _record(symbol: str, as_of: datetime, quote: Quote | None, profile: Profile | None, periods: list[boundary.FiscalPeriod],
            notes: list[str], *, provider: str, provider_reason: str, latest_filing: str | None = None,
            check: boundary.CrossCheck | None = None, taxonomy: str = "", filing_currency: str | None = None,
            submission: boundary.Submission | None = None, submissions_unavailable: str | None = None) -> boundary.Financials:
    """With [filing_currency] (filed statements) the statement currency is the filing's unit,
    the vendor's is recorded beside it, and the single currency basis holds iff the filing's
    unit is the trading currency."""
    q = quote_fields(quote, notes)
    financial_currency = q["financial_currency"] if filing_currency is None else filing_currency
    currency = q["currency"] if filing_currency is None else (filing_currency if filing_currency == q["trading_currency"] else None)
    return boundary.Financials(
        ticker=symbol,
        as_of=as_of.isoformat(timespec="seconds"),
        currency=currency,  # pyright: ignore[reportArgumentType]
        financial_currency=financial_currency,  # pyright: ignore[reportArgumentType]
        trading_currency=q["trading_currency"],  # pyright: ignore[reportArgumentType]
        price_unit=q["price_unit"],  # pyright: ignore[reportArgumentType]
        price_unit_divisor=q["price_unit_divisor"],  # pyright: ignore[reportArgumentType]
        price=q["price"],  # pyright: ignore[reportArgumentType]
        market_cap=q["market_cap"],  # pyright: ignore[reportArgumentType]
        country=profile.country if profile else None,
        industry=profile.industry if profile else None,
        periods=periods,
        notes=list(notes),
        provider=provider,
        taxonomy=taxonomy,
        vendor_financial_currency=None if filing_currency is None else q["financial_currency"],  # pyright: ignore[reportArgumentType]
        market_provider="yfinance",
        provider_reason=provider_reason,
        latest_filing=latest_filing,
        cross_check=check,
        submissions_latest_annual=submission,
        submissions_unavailable=submissions_unavailable,
    )


VENDOR_FRESHNESS_DAYS = 45  # the vendor's newest annual must end no earlier than the filing's period less this


class Lag:
    """companyfacts lags submissions: the filer has filed a newer annual than the facts know."""

    def __init__(self, submission: boundary.Submission, facts_end: str, facts_filed: str) -> None:
        self.submission = submission
        self.facts_end = facts_end
        self.facts_filed = facts_filed

    @property
    def text(self) -> str:
        s = self.submission
        return f"companyfacts lags submissions: {s.form} filed {s.filing_date} (period {s.report_date}) not yet in facts; facts end {self.facts_end}"


def lag_of(submission: boundary.Submission | None, periods: list[boundary.FiscalPeriod]) -> Lag | None:
    """The lag when submissions' newest annual was filed after the newest annual facts."""
    latest = fetch_sec.latest_filing(periods)
    if submission is None or not periods or latest is None or submission.filing_date <= latest:
        return None
    return Lag(submission, max(p.period_end for p in periods), latest)


def vendor_is_fresh(vendor: list[boundary.FiscalPeriod], submission: boundary.Submission) -> bool:
    """The vendor's newest annual column ends at or after the filing's period less 45 days."""
    if not vendor:
        return False
    newest = max(date.fromisoformat(p.period_end) for p in vendor)
    return (date.fromisoformat(submission.report_date) - newest).days <= VENDOR_FRESHNESS_DAYS


def fetch(symbol: str, as_of: datetime, sec: SecContext, *, depth: int = fetch_sec.PERIODS_DEFAULT,
          declared_cik: str | None = None) -> tuple[boundary.Financials, boundary.Financials | None]:
    """The record, and for an XBRL-primary name the vendor's shadow record beside it. [depth] is
    the number of annual periods the routed model needs (periods_needed); [declared_cik] the
    universe entry's cik (22)."""
    notes: list[str] = []
    ticker = yf.Ticker(symbol)
    quote, profile = _info(ticker, notes)
    vendor = vendor_periods(ticker, notes)

    cik, cik_source = cik_of(symbol, sec.tickers, declared_cik)
    if cik is None:
        return _record(symbol, as_of, quote, profile, vendor, notes, provider="yfinance",
                       provider_reason=f"no SEC filings for {symbol}: not in company_tickers.json"), None
    facts = fetch_sec.companyfacts(cik, sec.user_agent)
    submission, submissions_unavailable = fetch_sec.latest_annual_submission(fetch_sec.submissions(cik, sec.user_agent))
    decision = fetch_sec.decide(facts, sec.tags)
    if not decision.xbrl or decision.currency is None:
        return _record(symbol, as_of, quote, profile, vendor, notes, provider="yfinance",
                       provider_reason=f"CIK {cik}: {decision.reason}", submission=submission, submissions_unavailable=submissions_unavailable), None

    filed_notes = list(notes)
    periods = fetch_sec.periods_from_facts(decision.facts, sec.tags, sec.definitions, filed_notes, taxonomy=decision.taxonomy, unit=decision.currency, depth=depth)
    filed_notes.append(f"CIK {cik} ({cik_source}): {len(decision.facts)} {decision.taxonomy} tags; {len(periods)} annual periods in {decision.currency}, {depth} asked for")
    reason = f"CIK {cik} ({cik_source}): {decision.reason}" if declared_cik else f"CIK {cik}: {decision.reason}"
    lag = lag_of(submission, periods)
    if lag is not None:
        facts_age = (as_of.date() - date.fromisoformat(lag.facts_filed)).days
        if facts_age <= sec.tags.max_filing_age_days:
            filed_notes.append(f"{lag.text}; the facts are {facts_age} days old, within max_filing_age_days {sec.tags.max_filing_age_days}, so the filing is kept")
        elif vendor_is_fresh(vendor, lag.submission):
            # The decision, on the record: the filer has filed a newer annual than companyfacts
            # knows, the facts are past the gate, and the vendor's statements reach the filing's
            # period. The vendor's statements follow the same definitions as every vendor record.
            common = match_period(periods[0], vendor)
            check = (cross_check(common, periods[0], sec.tags.cross_check_threshold, fetch_sec.PROVIDER) if common is not None
                     else boundary.CrossCheck(provider=fetch_sec.PROVIDER, period_end=max(p.period_end for p in vendor), secondary_period_end="no common period",
                                              threshold=sec.tags.cross_check_threshold, fields=[], disagreements=0))
            lagged_notes = list(notes) + [f"CIK {cik}: {decision.reason}; the newest annual facts ({lag.facts_end}, filed {lag.facts_filed}) are {facts_age} days old"]
            return _record(symbol, as_of, quote, profile, vendor, lagged_notes, provider="yfinance", provider_reason=lag.text,
                           check=check, submission=submission), None
        else:
            reason += f"; {lag.text}; the vendor's newest annual ({max((p.period_end for p in vendor), default='none')}) predates the filing's period, so the filed statements are kept"
    check: boundary.CrossCheck | None = None
    vendor_currency = quote.financial_currency if quote else None
    if periods and vendor_currency != decision.currency:
        filed_notes.append(f"cross-check: not run, the vendor's statements are in {vendor_currency} and the filing's in {decision.currency}")
    elif periods:
        match = match_period(periods[0], vendor)
        if match is not None:
            check = cross_check(periods[0], match, sec.tags.cross_check_threshold, "yfinance")
        else:
            filed_notes.append(f"cross-check: the vendor has no period within {CROSS_CHECK_MAX_DAYS} days of {periods[0].period_end}")
    primary = _record(symbol, as_of, quote, profile, periods, filed_notes, provider=fetch_sec.PROVIDER,
                      provider_reason=reason, latest_filing=fetch_sec.latest_filing(periods), check=check,
                      taxonomy=decision.taxonomy, filing_currency=decision.currency,
                      submission=submission, submissions_unavailable=submissions_unavailable)
    shadow = _record(symbol, as_of, quote, profile, vendor, notes, provider="yfinance",
                     provider_reason="shadow of an XBRL-primary record, for the provider diff")
    return primary, shadow


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("tickers", nargs="+", help="symbols as the vendor spells them, e.g. AAPL BRK-B")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help=f"output directory (default: {DEFAULT_OUT})")
    parser.add_argument("--universe", type=Path, default=None, help="the universe file the tickers are declared in: its class sets the period depth, its cik the filer (22)")
    args = parser.parse_args(argv)
    tickers: list[str] = [str(t).upper() for t in args.tickers]
    out: Path = args.out
    universe_path: Path | None = args.universe
    out.mkdir(parents=True, exist_ok=True)
    as_of = datetime.now(timezone.utc)
    sec = SecContext()
    entries = {e.ticker.upper(): e for e in universe_file.load(universe_path).tickers} if universe_path else {}

    for symbol in tickers:
        entry = entries.get(symbol)
        financials, shadow = fetch(symbol, as_of, sec,
                                   depth=periods_needed(entry.entity_class if entry else None, sec.admissibility, sec.params),
                                   declared_cik=entry.cik if entry else None)
        # allow_nan=False: a NaN that slipped through is a bug here, not invalid JSON
        # for the other side to choke on.
        text = financials.to_json_string(indent=2, allow_nan=False)
        boundary.Financials.from_json_string(text)  # parse-time type check of what we wrote
        path = out / f"{symbol}.json"
        path.write_text(text + "\n")
        shadow_path = out / f"{symbol}.shadow-yfinance.json"
        if shadow is not None:
            shadow_path.write_text(shadow.to_json_string(indent=2, allow_nan=False) + "\n")
        elif shadow_path.exists():
            shadow_path.unlink()
        summary = (
            f"{symbol}: {financials.provider}, {len(financials.periods)} period(s), currency={financials.currency}, "
            f"price={financials.price}, country={financials.country}"
        )
        if financials.cross_check is not None:
            summary += f", cross-check {financials.cross_check.disagreements} of {len(financials.cross_check.fields)} fields disagree"
        if financials.provider != fetch_sec.PROVIDER:
            summary += f" ({financials.provider_reason})"
        print(f"{summary} -> {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
